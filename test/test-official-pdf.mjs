// Test 1: Typical English Name
{
  console.log("--- Test 1: Typical English Name ---");
  const result = await generateOfficialCertificatePdf({
    recipientName: "Alex Chen",
    certificateId: "ALGO-2026-HACK-7892",
    issueDate: "4 October 2026",
    preferPublicDomain: true,
  });

  assert.ok(result.pdfBytes.length > 50000, "PDF should be a substantial binary file");
  // Check PDF magic header %PDF-1.
  const header = Buffer.from(result.pdfBytes.subarray(0, 5)).toString("ascii");
  assert.strictEqual(header, "%PDF-", "Generated bytes must start with %PDF- header");

  // Verify documentHash is genuine SHA-256 over pdfBytes
  const expectedDocHash = crypto
    .createHash("sha256")
    .update(Buffer.from(result.pdfBytes))
    .digest("hex");
  assert.strictEqual(result.documentHash, expectedDocHash, "documentHash must match SHA-256 of final PDF bytes");
  assert.notStrictEqual(result.documentHash, result.metadataHash, "documentHash and metadataHash must be distinct");

  // Save to test output for visual inspection
  fs.writeFileSync(path.join(outputDir, "test1-alex-chen.pdf"), Buffer.from(result.pdfBytes));
  console.log(`✓ Test 1 Passed: Generated test1-alex-chen.pdf (${result.pdfBytes.length} bytes, hash: ${result.documentHash.slice(0, 16)}...)`);
}

